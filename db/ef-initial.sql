-- EF Core 8 產生的初始 migration SQL
--   產生指令：dotnet ef migrations script -o ../../db/ef-initial.sql
--   ⚠️ 這是「快照」檔。重跑上面那個指令會蓋掉，包含下面所有註解。
--
-- 註解 ★ 是比對 db/schema.sql 之後的答案，供事後複習。
-- 完整說明見：docs/progress/Day3-筆記-EF產出vs手寫SQL.md
